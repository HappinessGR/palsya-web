// Builds locales/REVIEW.md — the native-speaker review list — from
// locales/review/<locale>.json (written by the translators), showing the
// English source next to the current translation for every entry.
//   node scripts/i18n-review.mjs
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..", "locales");
const names = { pt: "Português (pt-PT)", nl: "Nederlands (nl-NL)", es: "Español (es-ES)", fr: "Français (fr-FR)", de: "Deutsch (de-DE)", af: "Afrikaans (af-ZA)" };
const order = { clinical: 0, legal: 1, terminology: 2, tone: 3 };

function loadMessages(locale) {
  const dir = path.join(root, locale);
  const all = {};
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".json"))) all[f.replace(/\.json$/, "")] = JSON.parse(fs.readFileSync(path.join(dir, f), "utf8"));
  return all;
}
const get = (obj, key) => key.split(".").reduce((o, k) => (o && typeof o === "object" ? o[k] : undefined), obj);
const cell = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const leaves = (v, prefix) =>
  v && typeof v === "object" ? Object.entries(v).flatMap(([k, x]) => leaves(x, `${prefix}.${k}`)) : [[prefix, v]];

const en = loadMessages("en");
let md = `# Translation review list

Generated by \`node scripts/i18n-review.mjs\` from \`locales/review/<locale>.json\`.
Every entry marked **REVIEW** needs a native speaker to check it; **clinical** entries need a
native-speaking clinician (physiotherapist or physician), **legal** entries need whoever signs
off consent and privacy wording. Edit the translation in \`locales/<locale>/<namespace>.json\`
(the key's first segment is the namespace file), then delete the entry from
\`locales/review/<locale>.json\` and re-run this script.

Decisions to confirm across all languages:
- Emergency number in \`assessment.flags.limb.body\`: de and es name 112; the others keep "your local emergency number".
- Cited press headlines (\`stories.press.*.headline\`) are translated; the German *Der Standard* headline is kept as published everywhere. Consider keeping the peer-reviewed paper title (\`stories.press.jdr.headline\`) in its original English.
- Formal address throughout (Sie / vous / u / usted / pt-PT third person / u).

`;

// Clinical/legal wording is the same content in every language, so any key
// one translator flagged as clinical or legal is reviewed in all of them.
const lists = Object.fromEntries(
  Object.keys(names).map((l) => {
    const file = path.join(root, "review", `${l}.json`);
    return [l, fs.existsSync(file) ? JSON.parse(fs.readFileSync(file, "utf8")) : []];
  }),
);
const shared = new Map();
for (const list of Object.values(lists))
  for (const e of list) if ((e.reason === "clinical" || e.reason === "legal") && !shared.has(e.key)) shared.set(e.key, e.reason);

const counts = {};
for (const locale of Object.keys(names)) {
  const messages = loadMessages(locale);
  const seen = new Set();
  const rows = [];
  const entries = [...lists[locale], ...[...shared].map(([key, reason]) => ({ key, reason, note: "" }))];
  for (const entry of entries) {
    // An entry may name a leaf key or a whole subtree (e.g. "library.exercises").
    const enValue = get(en, entry.key);
    if (enValue === undefined) continue; // stale (key renamed/removed)
    for (const [key, source] of leaves(enValue, entry.key)) {
      if (seen.has(key)) continue;
      seen.add(key);
      rows.push({ key, reason: entry.reason ?? "clinical", note: entry.note ?? "", source, target: get(messages, key) });
    }
  }
  rows.sort((a, b) => (order[a.reason] ?? 9) - (order[b.reason] ?? 9) || a.key.localeCompare(b.key));
  counts[locale] = rows.reduce((c, r) => ((c[r.reason] = (c[r.reason] ?? 0) + 1), c), { total: rows.length });

  md += `\n## ${names[locale]} — ${rows.length} entries\n\n| | Key | Reason | English | Translation | Translator's note |\n|---|---|---|---|---|---|\n`;
  for (const r of rows) md += `| REVIEW | \`${r.key}\` | ${r.reason} | ${cell(r.source)} | ${cell(r.target)} | ${cell(r.note)} |\n`;
}

fs.writeFileSync(path.join(root, "REVIEW.md"), md);
console.table(counts);
